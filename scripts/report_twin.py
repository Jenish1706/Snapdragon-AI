#!/usr/bin/env python3
# ruff: noqa: ISC004  (long markdown paragraphs are written as adjacent string literals)
"""Render docs/TWIN.md from results/twin/*.csv (run scripts/fit_twin.py first)."""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "results/twin"
SHORT = {"Samsung Galaxy S26": "Galaxy S26", "Samsung Galaxy S25": "Galaxy S25", "Snapdragon X Elite CRD": "X Elite CRD",
         "Snapdragon X2 Elite CRD": "X2 Elite CRD", "OnePlus Pad 4": "Pad 4", "OnePlus Nord CE4": "Nord CE4"}


def rows(name: str) -> list[dict]:
    p = T / name
    return list(csv.DictReader(p.open())) if p.exists() else []


def table(head: list[str], body: list[list]) -> str:
    return "\n".join(["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)] +
                     ["| " + " | ".join(str(c) for c in r) + " |" for r in body])


def main() -> None:
    lomo = [r for r in rows("lomo_summary.csv")]
    tr = rows("transfer_summary.csv")
    fits = rows("fits.csv")
    stages = sorted({r["stage"] for r in fits})
    parts = ["# SnapTwin: llama.cpp performance model and held-out error", "",
             "Generated by `scripts/report_twin.py` from `results/twin/*.csv`; do not edit by hand.", "",
             "## Model", "",
             "Per device and compute unit, SnapTwin predicts llama.cpp decode and prefill time from per-token model facts "
             "(weight bytes W, KV bytes K, matmul FLOPs F, attention FLOPs per query-key pair A, read from the GGUF headers):", "",
             "```", "decode per token at mean depth d:  t = a_w * W + a_kv * K * d + t0",
             "prefill of n tokens:               t = b_f * F * n + b_attn * A * n(n+1)/2 + b0", "```", "",
             "Coefficients are non-negative least squares on relative error. 1/a_w is the unit's effective weight bandwidth. "
             "To predict another chip the fitted efficiencies and overheads are kept, the bandwidth terms are rescaled by nominal "
             "bandwidth, and the compute terms by a compute ratio (1 unless stated). Every transferred number is a prediction.", "",
             "## Data", "",
             "- Published: Qualcomm ai-hub-models `perf.yaml` for Qwen3-0.6B/1.7B/4B Q4_0 through GenieX's llama.cpp plugin "
             "(commit 7142bf55ee28, 22 Sep 2026), 129 rows on 8 devices, in `data/published/geniex_llamacpp_qwen3_q4_0.csv`. "
             "The Galaxy S26 is Snapdragon 8 Elite Gen 5 for Galaxy (sm8850-ad, HTP v81) and the S25 is 8 Elite for Galaxy "
             "(SM8750), per Qualcomm's `devices_and_chipsets.yaml`.",
             "- Assumption: each published cell is a prompt of context - 128 tokens followed by 128 generated tokens, as "
             "GenieX's QDC runner derives it; TTFT maxima in `perf.yaml` equal context / prefill rate for all 129 rows.",
             "- The Dragonwing IQ-X7181 rows equal the X Elite CRD rows in all 18 cells, so they are not an independent "
             "device and never train a model that predicts the X Elite.",
             "- Nominal bandwidth: `data/specs/bandwidth.csv` (X Elite 135, X2 Elite 152, X2 Elite Extreme 228 GB/s; phones 84.8).",
             "- Device sweeps: `results/<device>/llama-bench/*.jsonl` when present (Pad 4, Nord CE4).", ""]
    for stage in stages:
        parts += [f"## Within-device held-out error ({stage} fits)", "",
                  "Leave one model out: fit on the other Qwen3 sizes, predict the held-out model's cells. Median / max absolute "
                  "percentage error of time.", ""]
        body = defaultdict(dict)
        for r in lomo:
            if r["stage"] == stage:
                body[(SHORT.get(r["device"], r["device"]), r["unit"])][r["kind"]] = f"{r['median_ape_pct']} / {r['max_ape_pct']} % ({r['cells']})"
        parts += [table(["Device", "Unit", "Prefill", "Decode"], [[d, u, v.get("pp", "–"), v.get("tg", "–")]
                                                                  for (d, u), v in sorted(body.items())]), ""]
    parts += ["## Transfer to the PCs (held out)", "",
              "Fit on the source device, predict the target's published cells; the target rows never enter the fit. "
              "Median / max absolute percentage error of time; decode rescaled by nominal bandwidth, prefill with compute ratio 1.", ""]
    body = defaultdict(dict)
    for r in tr:
        body[(r["stage"], SHORT.get(r["source"], r["source"]), SHORT.get(r["target"], r["target"]),
              r["target_bw_label"] if "target_bw_label" in r else r["bw_label"], r["unit"])][r["kind"]] = \
            f"{r['median_ape_pct']} / {r['max_ape_pct']} %"
    parts += [table(["Stage", "Source", "Target", "Target bandwidth", "Unit", "Prefill", "Decode"],
                    [[s, a, b, (bw.replace("Snapdragon ", "").replace(" CRD", "") + (" (152 GB/s)" if "X2 Elite CRD" in bw else " (135 GB/s)" if "X Elite CRD" in bw else "")),
                      u, v.get("pp", "–"), v.get("tg", "–")] for (s, a, b, bw, u), v in sorted(body.items())]), ""]
    agg = defaultdict(list)
    for r in rows("transfer.csv"):
        if r["stage"] == "published->PC" and r["bw_label"] == r["target"]:
            agg[(r["unit"] if r["unit"] == "npu" else "cpu/gpu", r["kind"])].append(float(r["ape"]))
    if agg:
        import statistics

        med = {k: round(100 * statistics.median(v)) for k, v in agg.items()}
        parts += ["### What the held-out numbers say", "",
                  f"- Decode transfers by bandwidth on CPU and GPU: median error {med.get(('cpu/gpu', 'tg'), '–')} % over "
                  "all phone-to-PC cells, because those paths are bandwidth-bound.",
                  f"- NPU decode does not: median error {med.get(('npu', 'tg'), '–')} %. It is dominated by per-token "
                  "overheads that differ between Hexagon generations and between the phone and PC drivers.",
                  f"- Prefill does not transfer with compute ratio 1: CPU/GPU median error {med.get(('cpu/gpu', 'pp'), '–')} %, "
                  f"NPU {med.get(('npu', 'pp'), '–')} %. PC prefill needs a compute ratio (core count, clocks, HMX width) "
                  "that SnapTwin cannot infer from bandwidth.",
                  "- For the X2 Elite CRD, 152 GB/s fits the published decode better than 228 GB/s (see the rows above), "
                  "consistent with a non-Extreme part, although Qualcomm does not state the CRD's SKU.", ""]
    parts += ["## Fitted effective weight bandwidth", "",
              table(["Stage", "Device", "Unit", "Effective GB/s", "% of nominal", "Decode overhead t0 (ms)", "In-sample median error %"],
                    [[r["stage"], SHORT.get(r["device"], r["device"]), r["unit"], r["eff_weight_bw_gbs"], r["bw_utilisation_pct"],
                      f"{float(r['t0']) * 1e3:.2f}", r["in_sample_median_ape_pct"]] for r in fits]), ""]
    (ROOT / "docs/TWIN.md").write_text("\n".join(parts) + "\n")
    print("wrote docs/TWIN.md")


if __name__ == "__main__":
    main()
